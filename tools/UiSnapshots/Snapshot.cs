using System.Diagnostics;
using System.Globalization;
using Avalonia;
using Avalonia.Controls;
using Avalonia.Headless;
using Avalonia.Input;
using Avalonia.Markup.Xaml.Styling;
using Avalonia.Media.Imaging;
using Avalonia.Styling;
using Avalonia.Threading;

namespace PdfEditorApp.Plugins.CSharpEditor.Tools.UiSnapshots;

/// <summary>
/// The headless session: Avalonia with the Skia renderer but no screen and no running message loop, plus the few things
/// a snapshot needs: show a view in an off-screen window, let it settle, drive the mouse, and save what it drew.
/// </summary>
internal static class Snapshot
{
    private static readonly List<string> TempFolders = new();

    public static string OutputFolder { get; private set; } = string.Empty;

    // The Runner's App.axaml applies the studio's style bundle and palette to the whole application; FryPDF's doesn't. Compiled
    // XAML inlines the includes, so they are known by what they hold: the bundle's marker resource, the palette's background.
    private static void RemoveStudioStylesFromApplication()
    {
        var app = Application.Current!;
        for (int i = app.Styles.Count - 1; i >= 0; i--)
        {
            var styles = app.Styles[i] is StyleInclude include ? include.Loaded : app.Styles[i];
            if (styles is IResourceProvider provider && provider.TryGetResource(PdfEditorApp.Plugins.CSharpEditor.Controls.Common.StudioStyleSheet.MarkerKey, null, out _))
            {
                app.Styles.RemoveAt(i);
            }
        }

        var merged = app.Resources.MergedDictionaries;
        for (int i = merged.Count - 1; i >= 0; i--)
        {
            if (merged[i].TryGetResource("DsBgBrush", ThemeVariant.Dark, out _)) merged.RemoveAt(i);
        }

        if (PdfEditorApp.Plugins.CSharpEditor.Controls.Common.StudioStyleSheet.ApplicationHasIt)
        {
            throw new InvalidOperationException("FRY_PLUGIN_STYLES_ONLY: the studio's styles are still applied to the application.");
        }
    }

    public static void Start(Options options)
    {
        AppBuilder.Configure<PdfEditorApp.Plugins.CSharpEditor.Runner.App>()
            .UseSkia()
            // Draw real pixels with Skia; headless drawing would render nothing worth saving.
            .UseHeadless(new AvaloniaHeadlessPlatformOptions { UseHeadlessDrawing = false })
            .SetupWithoutStarting();

        // FRY_PLUGIN_STYLES_ONLY=1: render as the plugin does inside FryPDF, whose application has none of the studio's
        // styles or palette; the studio host then includes them for its own tree (StudioStyleSheet).
        if (Environment.GetEnvironmentVariable("FRY_PLUGIN_STYLES_ONLY") is { Length: > 0 }) RemoveStudioStylesFromApplication();

        if (options.Flag("light")) Application.Current!.RequestedThemeVariant = ThemeVariant.Light;
        if (options.Value("palette") is { } palette) ApplyGeneratedTheme(palette, dark: !options.Flag("light"));
        if (options.Value("layout") is { } layoutId)
        {
            // --layout <preset id or name>: every view drawn with that layout.
            var preset = PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.Theming.Layout.LayoutPresets.All
                .FirstOrDefault(p => p.Id.Equals(layoutId, StringComparison.OrdinalIgnoreCase) || p.Id.Equals("layout-" + layoutId, StringComparison.OrdinalIgnoreCase) || p.Name.Equals(layoutId, StringComparison.OrdinalIgnoreCase))
                ?? throw new ArgumentException($"No layout preset '{layoutId}'. Presets: {string.Join(", ", PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.Theming.Layout.LayoutPresets.All.Select(p => p.Id))}");
            PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.StudioAppContext.Instance.ThemeEngine.ApplyLayout(preset.Spec);
            Console.WriteLine($"Layout: {preset.Name}");
        }

        OutputFolder = Path.GetFullPath(options.Value("out") ?? DefaultOutputFolder());
        Directory.CreateDirectory(OutputFolder);
    }

    // --palette oklch|hct[:seed]: every view drawn under a theme generated by the palette studio.
    private static void ApplyGeneratedTheme(string value, bool dark)
    {
        var parts = value.Split(':');
        var kind = parts[0].Equals("hct", StringComparison.OrdinalIgnoreCase)
            ? PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.Theming.ColorMath.ColorEngineKind.Hct
            : PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.Theming.ColorMath.ColorEngineKind.Oklch;
        var seed = parts.Length > 1 && int.TryParse(parts[1], out var s) ? s : 1;
        var spec = PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.Theming.Palette.PaletteGenerator.Regenerate(
            new PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.Theming.Palette.PaletteSpec { Engine = kind, IsDark = dark, Seed = seed });
        var theme = PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.Theming.HarmonicColorGenerator.ThemeFromPalette(
            PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.Theming.Palette.PaletteGenerator.Generate(spec), 0);
        var engine = PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.StudioAppContext.Instance.ThemeEngine;
        engine.RegisterTheme(theme);
        engine.ApplyTheme(theme.Id);
        _trackWindows = true;
        Console.WriteLine($"Theme: {theme.Name} ({theme.Description})");
    }

    // With a generated theme, each window gets the theme layer the way the studio's host view does (another root, such
    // as a tool window, would otherwise take the layer away from the application).
    private static bool _trackWindows;

    /// <summary>Puts <paramref name="content"/> in an off-screen window of that size (the image size) and lets it lay out.</summary>
    public static Window Show(Control content, double width, double height)
    {
        var window = new Window { Width = width, Height = height, Content = content };
        if (_trackWindows) PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.StudioAppContext.Instance.ThemeEngine.TrackResourceRoot(window);
        window.Show();
        Settle();
        return window;
    }

    /// <summary>
    /// Runs the UI thread's queued work (bindings, layout, posted callbacks) for a few frames. Nothing else runs it:
    /// there is no message loop, so call this after anything that changes what's on screen.
    /// </summary>
    public static void Settle(int frames = 10)
    {
        for (int i = 0; i < frames; i++)
        {
            Dispatcher.UIThread.RunJobs();
            Thread.Sleep(30);
        }
    }

    /// <summary>
    /// Pumps the UI thread until <paramref name="condition"/> holds (true) or <paramref name="timeout"/> passes (false).
    /// Unlike <see cref="Settle"/> it keeps <c>DispatcherTimer</c>s ticking (hover delays, debounces): with no message
    /// loop, a due timer only fires when some other job runs, so it posts an empty one each frame.
    /// </summary>
    public static bool WaitFor(Func<bool> condition, TimeSpan timeout)
    {
        var stopwatch = Stopwatch.StartNew();
        while (!condition())
        {
            if (stopwatch.Elapsed > timeout) return false;
            Dispatcher.UIThread.Post(() => { }, DispatcherPriority.Background);
            Dispatcher.UIThread.RunJobs();
            Thread.Sleep(15);
        }
        return true;
    }

    /// <summary>
    /// Waits for async work while keeping the UI thread's queue moving. Never <c>await</c> instead: the continuation is
    /// queued on the UI thread, nothing runs that queue while the program waits, and it hangs at 0% CPU.
    /// </summary>
    public static void Wait(Task task)
    {
        while (!task.IsCompleted)
        {
            Dispatcher.UIThread.RunJobs();
            Thread.Sleep(5);
        }
        task.GetAwaiter().GetResult();
    }

    public static T Wait<T>(Task<T> task)
    {
        Wait((Task)task);
        return task.Result;
    }

    public static void EnsureExtensionsLoaded(PdfEditorApp.Plugins.CSharpEditor.Services.Languages.StudioLanguageServices languages, Options options)
    {
        var app = PdfEditorApp.Plugins.CSharpEditor.Services.Extensibility.StudioAppContext.Instance;
        app.LanguageServices = languages;

        Wait(app.ExtensionManager.DiscoverAndLoadFromDefaultLocationsAsync(enableHotReload: false));

        if (options.Value("extension") is { } extDir && Directory.Exists(extDir))
        {
            if (File.Exists(Path.Combine(extDir, "extension.json")))
            {
                Wait(app.ExtensionManager.LoadExtensionAsync(extDir, enableHotReload: false));
            }
            else
            {
                Wait(app.ExtensionManager.DiscoverAndLoadAllAsync(extDir, enableHotReload: false));
            }
        }

        var samplesExt = Path.Combine(Directory.GetCurrentDirectory(), "samples", "extensions");
        if (!Directory.Exists(samplesExt))
        {
            samplesExt = Path.Combine(AppContext.BaseDirectory, "samples", "extensions");
        }
        if (Directory.Exists(samplesExt))
        {
            Wait(app.ExtensionManager.DiscoverAndLoadAllAsync(samplesExt, enableHotReload: false));
        }
    }

    /// <summary>
    /// Applies <c>--hover</c>, then saves what the window drew as <c>{--name or defaultName}.png</c> and prints its path.
    /// Supports <c>--timestamp</c> to append a date-time stamp and <c>--unique</c> to avoid overriding existing files.
    /// </summary>
    public static string Save(Window window, Options options, string defaultName)
    {
        if (options.Value("hover") is { } hover) Hover(window, ParsePoint(hover));
        string baseName = options.Value("name") ?? defaultName;
        if (options.Flag("timestamp"))
        {
            baseName = $"{baseName}_{DateTime.Now:yyyyMMdd_HHmmss}";
        }
        else if (options.Flag("unique"))
        {
            baseName = GetUniqueName(OutputFolder, baseName);
        }
        return Save(window, baseName);
    }

    /// <summary>Finds an unused file name by appending an incremental index if <c>baseName.png</c> already exists.</summary>
    public static string GetUniqueName(string folder, string baseName)
    {
        string candidate = baseName;
        int counter = 1;
        while (File.Exists(Path.Combine(folder, candidate + ".png")))
        {
            candidate = $"{baseName}_{counter++}";
        }
        return candidate;
    }

    public static string Save(Window window, string name)
    {
        Settle(2);
        using var frame = window.CaptureRenderedFrame() ?? throw new InvalidOperationException("The window rendered nothing.");
        string path = Path.Combine(OutputFolder, name + ".png");
        frame.Save(path, PngBitmapEncoderOptions.Default);
        Console.WriteLine(path);
        return path;
    }

    /// <summary>Moves the mouse to <paramref name="point"/> (window coordinates), so hover styles show.</summary>
    public static void Hover(Window window, Point point)
    {
        window.MouseMove(point);
        Settle(6);
    }

    /// <summary>Presses the left button at <paramref name="from"/>, moves by <paramref name="by"/> in small steps and lets go.</summary>
    public static void Drag(Window window, Point from, Vector by, int steps = 8)
    {
        window.MouseMove(from);
        window.MouseDown(from, MouseButton.Left);
        for (int step = 1; step <= steps; step++)
        {
            window.MouseMove(from + by * step / steps);
            Dispatcher.UIThread.RunJobs();
        }
        window.MouseUp(from + by, MouseButton.Left);
        Settle(3);
    }

    /// <summary>Adds the plugin's style sheets to a control shown on its own, outside the view that normally includes them.</summary>
    public static void AddPluginStyles(Control control, params string[] styleFiles)
    {
        foreach (string file in styleFiles)
        {
            control.Styles.Add(new StyleInclude(new Uri("avares://UiSnapshots/")) { Source = new Uri($"avares://CSharpEditorPlugin/{file}") });
        }
    }

    /// <summary>A throwaway folder (deleted on exit) for storage and progress, so snapshots never touch your real data.</summary>
    public static string TempFolder(string purpose)
    {
        string folder = Path.Combine(Path.GetTempPath(), "UiSnapshots", $"{purpose}_{Guid.NewGuid():N}");
        TempFolders.Add(folder);
        return folder;
    }

    public static void DeleteTempFolders()
    {
        foreach (string folder in TempFolders)
        {
            try
            {
                if (Directory.Exists(folder)) Directory.Delete(folder, recursive: true);
            }
            catch (IOException)
            {
                // Something still has a file open; the OS cleans the temp folder eventually.
            }
        }
    }

    // "x,y" in window coordinates.
    private static Point ParsePoint(string text)
    {
        var parts = text.Split(',');
        if (parts.Length == 2 &&
            double.TryParse(parts[0], NumberStyles.Float, CultureInfo.InvariantCulture, out double x) &&
            double.TryParse(parts[1], NumberStyles.Float, CultureInfo.InvariantCulture, out double y))
        {
            return new Point(x, y);
        }
        throw new ArgumentException($"--hover wants x,y in window pixels, like 700,70; not '{text}'.");
    }

    // tools/UiSnapshots/out in the repository (git ignores it), found by walking up from the build output.
    private static string DefaultOutputFolder()
    {
        for (var folder = new DirectoryInfo(AppContext.BaseDirectory); folder != null; folder = folder.Parent)
        {
            if (File.Exists(Path.Combine(folder.FullName, "CSharpEditorPlugin.slnx")))
            {
                return Path.Combine(folder.FullName, "tools", "UiSnapshots", "out");
            }
        }
        return Path.Combine(AppContext.BaseDirectory, "out");
    }
}
